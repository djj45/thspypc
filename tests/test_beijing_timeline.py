def test_build_beijing_timeline_query_matches_official_frame():
    frame = build_beijing_timeline_query("920002", seq=0x01CB)
    # FDF 声明长度约定不同（官方 body-1，我们 len(body)，服务端均接受），
    # 子帧头与查询文本必须逐字节一致。
    assert frame[12:] == OFFICIAL_REQ_920002[12:]
    assert frame[12:25] == b"\x09\x00\x16\x00\x00\xcb\x01\x12\x00\x09\x00\x00\x01"


def test_beijing_seq_rolls():
    first = next_beijing_timeline_seq()
    second = next_beijing_timeline_seq()
    assert second - first == 2


def test_beijing_datatype_is_official_24_field_set():
    assert BEIJING_TIMELINE_DATATYPE[:4] == [7, 8, 9, 10]
    assert 262763 in BEIJING_TIMELINE_DATATYPE
    assert len(BEIJING_TIMELINE_DATATYPE) == 24


def test_parse_beijing_minute_response_golden():
    body = BSE_MINUTE_RESPONSE_920118[12:]  # strip FDF header
    assert body[:1] == b"\x0a"

    records = parse_index_timeline_response(body)

    assert len(records) == 228
    assert all(row["code"] == "920118" for row in records)
    first = records[0]
    # 字段子集：1,7,13,19,11,74,9,8；无 dt14/dt15/dt227/dt229（无大单/力量）
    assert first["bar_index"] == 132727394
    assert first["dt10"] == pytest.approx(22.01)  # dt11 别名
    assert first["dt11"] == pytest.approx(22.01)
    assert first["dt7"] == pytest.approx(22.04)
    assert first["dt13"] == 200
    assert first["dt19"] == 4402
    assert "dt14" not in first
    assert "dt15" not in first
    assert "dt227" not in first
    last = records[-1]
    assert last["bar_index"] == 132727731
    assert last["dt10"] == pytest.approx(22.06)
    assert last["dt13"] == 1351


